/**
 * Seal the friend packs (run with: pnpm tsx tools/seal-egg-packs.mjs <plaintext.json>)
 *
 * The plaintext file is the only place the names, the jokes and the passphrases exist together, and
 * it MUST NOT be committed — keep it outside the repo. This writes
 * `apps/server/src/eggs/packs.ts`, which is the sealed half and is the only half that ships.
 *
 * Input shape:
 *
 *   [ { "id": "p1", "passphrase": "…", "pack": { "group": "…", "labels": [ … ], "greetings": [ … ] } } ]
 *
 * Ids are opaque and stable. Keep an id the same across re-seals: it is what the app remembers
 * against a stored passphrase, so renaming one asks every friend to type their word again.
 *
 * Re-running re-seals everything with fresh salts and IVs, which is correct — the ciphertext
 * changing on every run is what an authenticated cipher with a random nonce looks like, and the
 * diff saying "everything changed" is not a bug to fix by reusing nonces.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// Run under `tsx` so these TypeScript imports resolve: `pnpm tsx tools/seal-egg-packs.mjs <file>`.
const { sealPack } = await import(path.join(repoRoot, "apps/server/src/eggs/seal.ts"));
const { EggPackSchema } = await import(path.join(repoRoot, "packages/contracts/src/egg-pack.ts"));

const input = process.argv[2];
if (!input) { console.error("usage: pnpm tsx tools/seal-egg-packs.mjs <plaintext.json>"); process.exit(64); }

const entries = JSON.parse(fs.readFileSync(input, "utf8"));
const seen = new Set();
const sealed = entries.map((e) => {
  if (!e.id || !e.passphrase) throw new Error(`every entry needs an id and a passphrase: ${JSON.stringify(e).slice(0, 80)}`);
  if (seen.has(e.id)) throw new Error(`duplicate id: ${e.id}`);
  seen.add(e.id);
  const parsed = EggPackSchema.safeParse(e.pack);
  if (!parsed.success) throw new Error(`${e.id}: ${parsed.error.issues.map((i) => `${i.path.join(".")} ${i.message}`).join("; ")}`);
  // The tense rule `run-label.test.tsx` holds the shipped labels to, checked here so a pack cannot
  // carry a pair the app would draw as two unrelated verbs.
  for (const l of parsed.data.labels) {
    const [, ...pt] = l.present.split(" ");
    const [, ...ps] = l.past.split(" ");
    if (pt.join(" ") !== ps.join(" ")) throw new Error(`${e.id}: "${l.present}" / "${l.past}" — the tail after the verb has to match`);
    if (l.present === l.past) throw new Error(`${e.id}: "${l.present}" is the same in both tenses`);
  }
  return sealPack(e.passphrase, e.id, parsed.data);
});

const out = path.join(repoRoot, "apps/server/src/eggs/packs.ts");
fs.writeFileSync(out, `import type { SealedEggPack } from "@realm/contracts";

/**
 * The sealed friend packs. GENERATED by \`tools/seal-egg-packs.mjs\` — do not edit by hand.
 *
 * Every one of these is a group of real people's names and in-jokes, encrypted under a word that
 * group already knows. Nothing here is readable from the repository, which is the point: Realm is
 * open source and these are not Realm's jokes to publish. See \`egg-pack.ts\` for what the sealing
 * does and does not promise.
 *
 * The ids are opaque and stable. A pack's id is what a remembered passphrase is stored against, so
 * renaming one asks its group to type their word again.
 */
export const EGG_PACKS: readonly SealedEggPack[] = ${JSON.stringify(sealed, null, 2)};
`);
console.log(`sealed ${sealed.length} pack(s) → ${path.relative(repoRoot, out)}`);
for (const e of entries) console.log(`  ${e.id}  ${e.pack.labels.length} label(s), ${(e.pack.greetings ?? []).length} greeting(s)`);
