import { rpc } from "../rpc/client";
import { getTerminalHub } from "../panes/terminal-hub";
import type { Api } from "./store";

/** The real Api: realm-server over WebSocket plus the Electron/xterm platform seams.
 *  Kept out of store.ts so the store (and its tests) never pull in xterm or the rpc singleton. */
export const liveApi = (): Api => ({
  listProfiles: () => rpc().call("profiles.list", {}),
  createProfile: (name) => rpc().call("profiles.create", { name }),
  listSpaces: () => rpc().call("spaces.list", {}),
  listItems: (spaceId) => rpc().call("items.list", { spaceId }),
  listAllItems: () => rpc().call("items.listAll", {}),
  search: (profileId, query) => rpc().call("search.query", { profileId, query }),
  listProjects: (spaceId) => rpc().call("projects.list", { spaceId }),
  listEnvironments: (spaceId) => rpc().call("environments.list", { spaceId }),
  createWorktree: (spaceId, title) => rpc().call("environments.createWorktree", { spaceId, title }),
  createSpace: (input) => rpc().call("spaces.create", input),
  updateSpace: (input) => rpc().call("spaces.update", input),
  reorderSpaces: async (ids) => { await rpc().call("spaces.reorder", { ids }); },
  deleteSpace: async (id) => { await rpc().call("spaces.delete", { id }); },
  createProject: (spaceId, name, rootPath) => rpc().call("projects.create", { spaceId, name, rootPath }),
  setLayout: (id, layout) => rpc().call("spaces.setLayout", { id, layout }),
  setGroups: (id, groups) => rpc().call("spaces.setGroups", { id, groups }),
  createTerminal: (spaceId) => rpc().call("terminals.create", { spaceId }),
  createBrowser: (spaceId) => rpc().call("browsers.create", { spaceId }),
  createDocuments: (spaceId, environmentId) => rpc().call("documents.create", environmentId ? { spaceId, environmentId } : { spaceId }),
  getDocuments: (documentsId) => rpc().call("documents.get", { documentsId }),
  setDocumentTabs: (documentsId, openPaths, activePath) => rpc().call("documents.setTabs", { documentsId, openPaths, activePath }),
  detachDocuments: async (documentsId) => { await rpc().call("documents.detach", { documentsId }); },
  listDocumentEntries: async (documentsId, dir) => (await rpc().call("documents.list", { documentsId, dir })).entries,
  readDocument: (documentsId, path) => rpc().call("documents.read", { documentsId, path }),
  writeDocument: (documentsId, path, text, baseHash) => rpc().call("documents.write", { documentsId, path, text, baseHash }),
  createDocumentFile: (documentsId, path, kind, title) => rpc().call("documents.createFile", { documentsId, path, kind, title }),
  updateItem: (input) => rpc().call("items.update", input),
  deleteItem: async (id) => { await rpc().call("items.delete", { id }); },
  getSetting: async (key) => (await rpc().call("settings.get", { key })).value,
  setSetting: async (key, value) => { await rpc().call("settings.set", { key, value }); },
  machineName: async () => (await rpc().call("system.info", {})).machineName,
  pickFolder: () => window.realm.pickFolder(),
  pickFiles: () => window.realm.pickFiles(),
  listIconAssets: (profileId) => rpc().call("iconAssets.list", { profileId }),
  generateIconAsset: (profileId, prompt) => rpc().call("iconAssets.generate", { profileId, prompt }),
  pickIconImage: () => window.realm.pickIconImage(),
  uploadIconAsset: (profileId, path) => rpc().call("iconAssets.upload", { profileId, path }),
  deleteIconAsset: async (id) => { await rpc().call("iconAssets.delete", { id }); },
  pathForFile: (file) => window.realm.pathForFile(file),
  saveTempAttachment: (name, mime, bytes) => window.realm.saveTempAttachment(name, mime, bytes),
  disposeTerminal: (terminalId) => getTerminalHub().dispose(terminalId),
  listSessions: (spaceId) => rpc().call("sessions.list", { spaceId }),
  listAllSessions: () => rpc().call("sessions.listAll", {}),
  getSession: (id) => rpc().call("sessions.get", { id }),
  createSession: (input) => rpc().call("sessions.create", input),
  forkSession: (checkpointId) => rpc().call("sessions.fork", { checkpointId }),
  listSkills: (spaceId) => rpc().call("skills.list", { spaceId }),
  listSkillSources: (spaceId) => rpc().call("skills.sources", { spaceId }),
  addSkillScanRoot: async (path) => { await rpc().call("skills.addScanRoot", { path }); },
  removeSkillScanRoot: async (path) => { await rpc().call("skills.removeScanRoot", { path }); },
  setSkillEnabled: async (spaceId, id, enabled) => { await rpc().call("skills.setEnabled", { spaceId, id, enabled }); },
  promoteSkill: async (spaceId, id) => { await rpc().call("skills.promote", { spaceId, id }); },
  demoteSkill: async (spaceId, id) => { await rpc().call("skills.demote", { spaceId, id }); },
  testMcpServer: (id) => rpc().call("mcp.test", { id }),
  getMemory: (spaceId) => rpc().call("memory.get", { spaceId }),
  setMemory: (spaceId, doc) => rpc().call("memory.set", { spaceId, doc }),
  setAgentsFile: (spaceId, enabled) => rpc().call("memory.setAgentsFile", { spaceId, enabled }),
  memorySources: (sessionId) => rpc().call("memory.sources", { sessionId }),
  sendMessage: async (id, text, attachments, mentions) => { await rpc().call("sessions.send", { id, text, attachments, mentions }); },
  interruptSession: async (id) => { await rpc().call("sessions.interrupt", { id }); },
  respondPermission: async (id, requestId, decision, answers) => { await rpc().call("sessions.respondPermission", { id, requestId, decision, ...(answers ? { answers } : {}) }); },
  setSessionOptions: (id, o) => rpc().call("sessions.setOptions", { id, ...o }),
  setSessionAgent: (id, agentKind) => rpc().call("sessions.setAgent", { id, agentKind }),
  setSessionEnvironment: (id, environmentId) => rpc().call("sessions.setEnvironment", { id, environmentId }),
  moveSessionToSpace: (id, spaceId) => rpc().call("sessions.moveToSpace", { id, spaceId }),
  sessionEvents: (id, afterSeq, limit) => rpc().call("sessions.events", { id, afterSeq, limit }),
  openSessionTerminal: (id) => rpc().call("sessions.openTerminal", { id }),
  writeTerminal: async (terminalId, data) => { await rpc().call("terminals.write", { terminalId, data }); },
  prefillTerminal: async (terminalId, command) => { await rpc().call("terminals.prefill", { terminalId, command }); },
  probeAgents: (force) => rpc().call("agents.probe", { force }),
  importScan: () => rpc().call("import.scan", {}),
  importApply: (selection) => rpc().call("import.apply", selection),
  tccProbe: () => window.realm.permissions.probe(),
  openTccPane: (pane) => window.realm.permissions.openSettings(pane),
  macAccessStatus: () => window.realm.macAccess.status(),
  macAccessGrant: (id) => window.realm.macAccess.grant(id),
  macAccessOpenSettings: (id) => window.realm.macAccess.openSettings(id),
  macAccessRevealApp: () => window.realm.macAccess.revealApp(),
  updateStatus: () => window.realm.updates.status(),
  checkUpdates: () => window.realm.updates.check(),
  installUpdate: () => window.realm.updates.install(),
  gitInfo: (cwd) => rpc().call("workspace.gitInfo", { cwd }),
  diff: (cwd) => rpc().call("workspace.diff", { cwd }),
  fileDiff: (cwd, path, staged) => rpc().call("workspace.fileDiff", { cwd, path, staged }),
  stagePaths: async (cwd, paths) => { await rpc().call("workspace.stage", { cwd, paths }); },
  unstagePaths: async (cwd, paths) => { await rpc().call("workspace.unstage", { cwd, paths }); },
  ship: (input) => rpc().call("workspace.ship", input),
  listShips: (spaceId, cursor = null, limit) => rpc().call("ships.list", { spaceId, cursor, ...(limit !== undefined ? { limit } : {}) }),
  createItem: (spaceId, kind, title, refId) => rpc().call("items.create", { spaceId, kind, title, refId }),
  worktreeStatus: (id) => rpc().call("environments.worktreeStatus", { id }),
  removeWorktree: async (id, acknowledge) => { await rpc().call("environments.removeWorktree", { id, acknowledge }); },
  listCheckpoints: (environmentId, sessionId) => rpc().call("checkpoints.list", { environmentId, sessionId }),
  captureCheckpoint: (environmentId, sessionId) => rpc().call("checkpoints.capture", { environmentId, sessionId }),
  previewCheckpoint: (id) => rpc().call("checkpoints.preview", { id }),
  restoreCheckpoint: (id, acknowledge) => rpc().call("checkpoints.restore", { id, acknowledge }),
  listMcpServers: (spaceId) => rpc().call("mcp.list", { spaceId }),
  addMcpServer: (input) => rpc().call("mcp.add", input),
  updateMcpServer: (input) => rpc().call("mcp.update", input),
  removeMcpServer: async (id) => { await rpc().call("mcp.remove", { id }); },
  setMcpEnabled: async (spaceId, id, enabled) => { await rpc().call("mcp.setEnabled", { spaceId, id, enabled }); },
  promoteMcpServer: async (spaceId, id) => { await rpc().call("mcp.promote", { spaceId, id }); },
  demoteMcpServer: async (spaceId, id) => { await rpc().call("mcp.demote", { spaceId, id }); },
  listMcpProviders: async (spaceId) => (await rpc().call("mcp.providers.list", { spaceId })).providers,
  setMcpProviderEnabled: async (spaceId, name, enabled) => { await rpc().call("mcp.setProviderEnabled", { spaceId, name, enabled }); },
  getProfileMemory: (profileId) => rpc().call("memory.getProfile", { profileId }),
  setProfileMemory: (profileId, doc) => rpc().call("memory.setProfile", { profileId, doc }),
  setProfileDocEnabled: (spaceId, enabled) => rpc().call("memory.setProfileDocEnabled", { spaceId, enabled }),
  mcpToolsList: (id) => rpc().call("mcp.tools.list", { id }),
  setMcpAllowedTools: async (spaceId, id, tools) => { await rpc().call("mcp.setAllowedTools", { spaceId, id, tools }); },
  startMcpOauth: (id) => rpc().call("mcp.oauth.start", { id }),
  disconnectMcpOauth: async (id) => { await rpc().call("mcp.oauth.disconnect", { id }); },
  retryMcpServer: async (id) => { await rpc().call("mcp.retry", { id }); },
  mcpCallsList: (params) => rpc().call("mcp.calls.list", params),
  listNotifications: (cursor, limit) => rpc().call("notifications.list", { cursor, ...(limit !== undefined ? { limit } : {}) }),
  markNotificationsRead: (input) => rpc().call("notifications.markRead", input),
  requestReview: (environmentId) => rpc().call("review.request", { environmentId }),
  getReview: (environmentId) => rpc().call("review.get", { environmentId }),
  dismissReview: async (environmentId) => { await rpc().call("review.dismiss", { environmentId }); },
});
