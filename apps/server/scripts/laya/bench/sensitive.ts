/**
 * `sensitive` cases: one step — a tool, the element it acts on and what the agent says it is for —
 * and whether that step spends money, deletes or erases something, sends or shares something with
 * someone else, or enters a password, code or other secret. Those four are what the shadow asks
 * (`SENSITIVE_PARTS`), so they are the whole definition here; a step that only grants a permission or
 * signs out is none of them, and was left out rather than argued either way.
 *
 * The hard ones are the point. A tap that opens the Passwords pane, looks at Recently Deleted or clears
 * a search field reads like a sensitive word and is not; typing a code into a chat, or confirming a
 * trial that renews at a price, reads harmless and is. Elements are named as in `target.ts`, plus
 * `@path` for an element with no label.
 */
export type SensitivePart = "money" | "delete" | "send" | "secret";
export type SensitiveCase = { screen: string; element: string; intent: string; sensitive: boolean; part: SensitivePart | null; tool: string };

